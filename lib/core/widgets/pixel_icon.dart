/// Draws a [PixelIcons] glyph. Sizes that are multiples of 12 look sharpest.
class PixelIcon extends StatelessWidget {
  final PixelIcons icon;
  final double size;
  final Color color;

  /// A hard shadow under the icon, for icons on the bare background.
  final bool shadow;

  const PixelIcon(
    this.icon, {
    super.key,
    this.size = 12,
    this.color = AppColors.white,
    this.shadow = false,
  });

  @override
  Widget build(BuildContext context) => SizedBox.square(
        dimension: size,
        child: CustomPaint(painter: _IconPainter(icon, color, shadow)),
      );
}

typedef _Run = ({int x, int y, int length, String cell});

class _IconPainter extends CustomPainter {
  final PixelIcons icon;
  final Color color;
  final bool shadow;
  const _IconPainter(this.icon, this.color, this.shadow);

  static const _grid = 12;
  static final Map<PixelIcons, List<_Run>> _parsed = {};

  /// Neighbouring cells merged into one rectangle per run.
  static List<_Run> _runsOf(PixelIcons icon) =>
      _parsed[icon] ??= _parse(icon.art);

  static List<_Run> _parse(String art) {
    final runs = <_Run>[];
    final rows = art.split('\n');
    for (var y = 0; y < rows.length; y++) {
      final row = rows[y];
      var x = 0;
      while (x < row.length) {
        final cell = row[x];
        var end = x + 1;
        while (end < row.length && row[end] == cell) {
          end++;
        }
        if (cell != '.') runs.add((x: x, y: y, length: end - x, cell: cell));
        x = end;
      }
    }
    return runs;
  }

  @override
  void paint(Canvas canvas, Size size) {
    final unit = size.width / _grid;
    final runs = _runsOf(icon);
    final paint = Paint()..isAntiAlias = false;

    void draw(Offset shift, Color Function(String cell) colorOf) {
      for (final run in runs) {
        paint.color = colorOf(run.cell);
        canvas.drawRect(
          Rect.fromLTWH(run.x * unit + shift.dx, run.y * unit + shift.dy,
              run.length * unit, unit),
          paint,
        );
      }
    }

    if (shadow) draw(Offset(unit, unit), (_) => AppColors.ink);
    final glint = Color.lerp(color, const Color(0xFFFFFFFF), 0.65)!;
    final shade = Color.lerp(color, AppColors.ink, 0.5)!;
    draw(
      Offset.zero,
      (cell) => switch (cell) { 'o' => glint, 'x' => shade, _ => color },
    );
  }

  @override
  bool shouldRepaint(_IconPainter old) =>
      old.icon != icon || old.color != color || old.shadow != shadow;
}
